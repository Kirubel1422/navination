// Generates src/mocks/fixtures.gen.ts from contracts/examples so mock mode follows the contract.
// Each fixture is checked by TypeScript with `satisfies` against the generated API types.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const examples = join(here, "../../../contracts/examples");
const out = join(here, "../src/mocks/fixtures.gen.ts");
const check = process.argv.includes("--check");

const fixtures = {
  createSession: ["create_session", "CreateSessionResponse"],
  discoverReady: ["discover_ready", "Discovery"],
  discoverClarification: ["discover_needs_clarification", "Discovery"],
  discoverClarificationAnswer: ["discover_clarification_answer", "Discovery"],
  discoverNoMatch: ["discover_no_match", "Discovery"],
  serviceCard: ["get_service", "ServiceCard"],
  journey: ["create_journey", "Journey"],
  coachTurn: ["coach_turn", "CoachTurn"],
  coachInsufficient: ["coach_turn_insufficient_evidence", "CoachTurn"],
  handoff: ["create_handoff", "Handoff"],
  errorPrerequisites: ["error_prerequisites_incomplete", "ErrorEnvelope"],
  errorHandoffUnavailable: ["error_handoff_unavailable", "ErrorEnvelope"],
  errorContextStale: ["error_context_stale", "ErrorEnvelope"],
  openData: ["get_open_data", "OpenDataSummary"],
  discoverPersona: ["discover_persona_baby", "Discovery"],
  journeyPersona: ["create_journey_persona_baby", "Journey"],
  navigationGaps: ["get_navigation_gaps", "NavigationGaps"],
};

let source = `// GENERATED by scripts/sync-mock-fixtures.mjs from contracts/examples. Do not edit.\n`;
source += `// Synthetic demo data for mock mode only (IDs, tokens and timestamps are not real).\n`;
source += `import type { components } from "@/lib/api/schema.gen";\n\ntype S = components["schemas"];\n\n`;
for (const [name, [file, type]] of Object.entries(fixtures)) {
  const body = JSON.parse(readFileSync(join(examples, `${file}.response.json`), "utf8")).body;
  source += `export const ${name} = ${JSON.stringify(body, null, 2)} satisfies S["${type}"];\n\n`;
}

if (check) {
  const current = readFileSync(out, "utf8");
  if (current !== source) {
    console.error("src/mocks/fixtures.gen.ts is out of date. Run: pnpm mocks:sync");
    process.exit(1);
  }
  console.log("Mock fixtures are up to date.");
} else {
  writeFileSync(out, source);
  console.log(`Wrote ${out}`);
}
