EDU = ["mohesr-degree-recognition", "mofa-attestation-abroad", "degree-verification-partner"]


def patch_step(guest, journey, service_id, body):  # type: ignore[no-untyped-def]
    step = step_for(journey, service_id)
    return guest.patch(f"/journeys/{journey['id']}/steps/{step['id']}", json=body)


def rewrite_plan(edit):  # type: ignore[no-untyped-def]
    """A model that edits the scripted plan once (before any rejection)."""

    def hook(messages, tools, default):  # type: ignore[no-untyped-def]
        submitted = [c for c in default.tool_calls if c.name == "submit_plan"]
        if submitted and not was_rejected(messages):
            data = json.loads(submitted[0].arguments)
            edit(data)
            return turn(call("submit_plan", data))
        return None

    return HookModel(hook)


def test_stages_and_steps_are_generated_by_the_agent(guest):
    recorder = RecordingModel()
    set_provider_override(recorder)
    journey = guest.plan(DEGREE_QUERY, EDU)
    plan_payload = recorder.payloads[-1]
    assert plan_payload["REQUEST"] == DEGREE_QUERY
    assert {s["service_id"] for s in plan_payload["SELECTED"]} == set(EDU)
    assert any(
        r["prerequisite_service_id"] == "uae-pass-account" for r in plan_payload["VERIFIED_RULES"]
    )
    assert [s["title"] for s in journey["stages"]][:2] == ["Get ready", "Main applications"]
    assert all(s["order_group"] == i for i, s in enumerate(journey["stages"]))
    mofa = step_for(journey, "mofa-attestation-abroad")
    assert mofa["title"] and mofa["instructions"].startswith("Prepare and apply")
    assert [c["id"] for c in mofa["checklist"]] == [
        d["document_id"] for d in mofa["document_progress"]
    ]
    assert all(c["ai_generated"] for c in mofa["checklist"])
    assert any("generated by NaviNation's AI agent" in n for n in journey["notices"])


