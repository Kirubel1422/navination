def test_completion_rules_and_rollback(guest):
    journey = guest.plan(DEGREE_QUERY, ["mofa-attestation-abroad"])
    rejected = patch_step(guest, journey, "mofa-attestation-abroad", {"progress": "completed"})
    assert (
        rejected.status_code == 409
        and rejected.json()["error"]["code"] == "PREREQUISITES_INCOMPLETE"
    )
    assert (
        patch_step(
            guest, journey, "mofa-attestation-abroad", {"progress": "in_progress"}
        ).status_code
        == 200
    )
    journey = patch_step(guest, journey, "uae-pass-account", {"progress": "completed"}).json()
    assert step_for(journey, "mofa-attestation-abroad")["availability"] == "ready"
    journey = patch_step(
        guest, journey, "mofa-attestation-abroad", {"progress": "completed"}
    ).json()
    journey = patch_step(guest, journey, "uae-pass-account", {"progress": "in_progress"}).json()
    assert step_for(journey, "mofa-attestation-abroad")["progress"] == "not_started"
    assert any("moved back to not started" in n for n in journey["notices"])


def test_checklist_progress(guest):
    journey = guest.plan(DEGREE_QUERY, ["mofa-attestation-abroad"])
    mofa = step_for(journey, "mofa-attestation-abroad")
    first, second = (c["id"] for c in mofa["checklist"])
    response = patch_step(
        guest,
        journey,
        "mofa-attestation-abroad",
        {"document_progress": [{"document_id": first, "status": "have"}]},
    )
    statuses = {
        d["document_id"]: d["status"]
        for d in step_for(response.json(), "mofa-attestation-abroad")["document_progress"]
    }
    assert statuses == {first: "have", second: "unknown"}
    dup = [{"document_id": first, "status": "have"}, {"document_id": first, "status": "missing"}]
    assert (
        patch_step(
            guest, journey, "mofa-attestation-abroad", {"document_progress": dup}
        ).status_code
        == 422
    )
    unknown = [{"document_id": "other.c1", "status": "have"}]
    assert (
        patch_step(
            guest, journey, "mofa-attestation-abroad", {"document_progress": unknown}
        ).status_code
        == 422
    )
    assert patch_step(guest, journey, "mofa-attestation-abroad", {}).status_code == 422


