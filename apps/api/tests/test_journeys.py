def test_guard_moves_steps_the_agent_ordered_wrongly(guest):
    def put_uae_pass_last(data):  # type: ignore[no-untyped-def]
        steps = [st for stage in data["stages"] for st in stage["steps"]]
        uae = next(st for st in steps if st["service_id"] == "uae-pass-account")
        for stage in data["stages"]:
            stage["steps"] = [st for st in stage["steps"] if st is not uae]
        for st in steps:
            st["depends_on"] = []
        data["stages"] = [s for s in data["stages"] if s["steps"]]
        data["stages"].append(
            {
                "title": {"en": "Last", "ar": "أخيراً"},
                "description": {"en": "d", "ar": "و"},
                "steps": [uae],
            }
        )

    set_provider_override(rewrite_plan(put_uae_pass_last))
    journey = guest.plan(DEGREE_QUERY, ["mofa-attestation-abroad", "uae-pass-account"])
    groups = {s["service_card"]["service"]["id"]: s["order_group"] for s in journey["steps"]}
    assert groups["mofa-attestation-abroad"] > groups["uae-pass-account"]
    assert any(n.startswith('Moved "') for n in journey["notices"])
    assert len(journey["stages"]) == len({s["order_group"] for s in journey["steps"]})


