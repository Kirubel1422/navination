LIST_SEPARATOR = {"en": "; ", "ar": "؛ "}


def t(locale: str, key: str, **params: Any) -> str:
    template = MESSAGES[key].get(locale) or MESSAGES[key]["en"]
    return template.format(**params)


def render_notices(locale: str, notices: list[dict[str, Any]]) -> list[str]:
    return [t(locale, n["key"], **localize_params(locale, n.get("params", {}))) for n in notices]


def localize_params(locale: str, params: dict[str, Any]) -> dict[str, Any]:
    """Params may hold {"en": ..., "ar": ...} dicts that are resolved per locale."""
    out: dict[str, Any] = {}
    for key, value in params.items():
        if isinstance(value, dict) and "en" in value:
            out[key] = value.get(locale) or value["en"]
        else:
            out[key] = value
    return out


def field_name(locale: str, field: str) -> str:
    return FIELD_NAMES[field][locale]


def answer_text(locale: str, field: str, value: Any) -> str:
    key = str(value).lower() if isinstance(value, bool) else str(value)
    return VALUE_ANSWERS[field][key][locale]
